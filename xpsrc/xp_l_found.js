function ADD(L){ MIX(L); L.scenes.forEach(sc=>{ for(const k in (sc.items||{})){ const it=sc.items[k]; if(POPT.includes(it.type)&&!it.rot) it.rot=.01; if((it.type==='box'||it.type==='circle')&&LIGHT.includes(it.c)&&!it.cls) it.cls='t-note'; if(it.type==='note'&&DARKF.includes(it.c)&&!it.cls) it.cls='t-ink'; } }); XP.add(L); };
/* a board line: optional markers ! (accent), ~ (secondary, smaller), ^ (large), then @ to lay the line out left to right (√, powers, negatives) */
/* left-to-right override: the only mark that keeps √, powers and negative signs in place next to Arabic-Indic digits */
function LTR(s){ return '\u202D'+s+'\u202C'; }
