/* a scene from [title, [[say, lines[], note?], …]]; lines stack down the board and the board clears when it is full */
function scene([t,beats],slots=LY){ const items={}, out=[]; let slot=0, on=[], k=0, nk=0;
  beats.forEach(([say,lines=[],note])=>{ const b={say,show:[]};
    if(slot+lines.length>slots.length){ b.hide=on.slice(); on=[]; slot=0; }
    lines.forEach(l=>{ const id='l'+(k++); items[id]=line(l,slots[slot++]); b.show.push(id); on.push(id); });
    if(note){ const old=on.filter(x=>x[0]==='n'); if(old.length){ b.hide=(b.hide||[]).concat(old); on=on.filter(x=>x[0]!=='n'); } const id='n'+(nk++); items[id]=noteIt(note,322,nk); b.show.push(id); on.push(id); }
    out.push(b); });
  return {t,items,beats:out}; }
/* the closing "your turn" scene: the question sits high on the board, the option buttons below it, then the worked answer */
function ask(t,beats,A){ const sc=scene([t,beats],[84,130]); sc.items.ans=line('!'+A.ans,208); sc.items.tip=noteIt(A.tip,300,1);
  sc.ask={opts:A.o,a:A.a,right:A.r,wrong:A.w,show:['ans','tip']}; if(A.ltr) sc.ask.ltr=true; return sc; }
function B(sc,A){ return {goals:sc.map(s=>s[0]).concat(['تطبّق ما تعلمته في سؤال']),scenes:sc.map(s=>scene(s)).concat([ask(A.t||'دورك',A.b,A)])}; }

